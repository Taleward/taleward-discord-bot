export const texte: Record<Sprache, Record<TextSchluessel, string>> = { de, en };

export function t(
  sprache: Sprache,
  schluessel: TextSchluessel,
  werte: Record<string, string> = {},
): string {
  let s: string = texte[sprache][schluessel];
  for (const [k, v] of Object.entries(werte)) s = s.replaceAll(`{${k}}`, v);
  return s;
}

/** Beide Sprachen für Discords Lokalisierung von Befehlen. */
export function beide(schluessel: TextSchluessel): { de: string; "en-US": string; "en-GB": string } {
  return { de: de[schluessel], "en-US": en[schluessel], "en-GB": en[schluessel] };
}
